"""
Generate series-thru 2-port Touchstone (.s2p) files for the TEAM NOVA RF front-end passives.

Inductors (APV AHW2012C, 0805 wire-wound): lumped model fitted to the APV datasheet
    L  in series with  R(f) = DCR + k*sqrt(f)   (k chosen so Q matches the datasheet Q at its test freq)
    all in parallel with Cp                      (Cp chosen so the model resonates at the datasheet SRF)
Capacitors (FH 0805CG, C0G): C + ESL + ESR(f), typical 0805 C0G values (FH publishes no RF data):
    ESL = 0.8 nH, ESR = 0.10 ohm + 0.10 ohm*sqrt(f/100 MHz)
Resistor (FH 0805 thick film): R + 0.7 nH series, 0.05 pF parallel.

Every file is a SERIES-THRU 2-port (part between port 1 and port 2, 50 ohm):
    series use : port1 -> left node, port2 -> right node, Ref -> GND
    shunt  use : port1 -> node,      port2 -> GND,        Ref -> GND
"""
import numpy as np, os, sys
from scipy.optimize import brentq

OUT = sys.argv[1] if len(sys.argv) > 1 else "s2p_out"
os.makedirs(OUT, exist_ok=True)
Z0 = 50.0
f = np.unique(np.concatenate([np.linspace(1e6, 1e9, 1000), np.linspace(1e9, 6e9, 501)]))
w = 2 * np.pi * f

def write(name, Z, header):
    S11 = Z / (Z + 2 * Z0); S21 = 2 * Z0 / (Z + 2 * Z0)
    with open(os.path.join(OUT, name + ".s2p"), "w") as fh:
        for line in header: fh.write("! " + line + "\n")
        fh.write("! Series-thru 2-port: part connected between port 1 and port 2.\n")
        fh.write("# Hz S RI R 50\n")
        for fi, a, b in zip(f, S11, S21):
            fh.write(f"{fi:.6e} {a.real:.8e} {a.imag:.8e} {b.real:.8e} {b.imag:.8e} "
                     f"{b.real:.8e} {b.imag:.8e} {a.real:.8e} {a.imag:.8e}\n")

def ind_Z(L, Cp, dcr, k, ff):
    ww = 2 * np.pi * ff
    Zs = dcr + k * np.sqrt(ff) + 1j * ww * L
    Zc = 1 / (1j * ww * Cp)
    return Zs * Zc / (Zs + Zc)

# APV AHW2012C datasheet: (part, L nH, Q, Q test MHz, SRF MHz, DCR ohm, board designators)
INDS = [("AHW2012C-27NJTF", 27, 55, 500, 2580, 0.25, "L1"),
        ("AHW2012C-33NJTF", 33, 60, 500, 2150, 0.27, "L7 L8"),
        ("AHW2012C-68NJTF", 68, 60, 500, 1500, 0.38, "L4"),
        ("AHW2012C-82NJTF", 82, 65, 500, 1330, 0.42, "L2 L3"),
        ("AHW2012C-R39JTF", 390, 48, 250, 600, 1.50, "L6"),
        ("AHW2012C-R62JTF", 620, 23, 50, 320, 2.20, "L5")]
report = []
for pn, Ln, Q, fq, srf, dcr, des in INDS:
    L = Ln * 1e-9; Cp = 1 / ((2 * np.pi * srf * 1e6) ** 2 * L); fqh = fq * 1e6
    qfun = lambda k: (lambda z: z.imag / z.real)(ind_Z(L, Cp, dcr, k, np.array([fqh]))[0]) - Q
    k = brentq(qfun, 0, 10)
    Z = ind_Z(L, Cp, dcr, k, f)
    # checks
    q_chk = qfun(k) + Q
    srf_chk = f[np.argmax(np.abs(Z))] / 1e6
    L100 = ind_Z(L, Cp, dcr, k, np.array([100e6]))[0].imag / (2 * np.pi * 100e6) * 1e9
    write(f"APV_{pn}", Z, [f"APV {pn} {Ln} nH 0805 wire-wound ({des})",
          "Lumped model fitted to APV datasheet: Q=%d@%dMHz, SRF=%dMHz, DCR=%.2f ohm" % (Q, fq, srf, dcr),
          "Model: (L + DCR + k*sqrt(f)) || Cp ; L=%.3g H, Cp=%.3g F, k=%.3g" % (L, Cp, k),
          "Generated by make_s2p.py - an estimate, not a measurement"])
    report.append(f"{pn:18s} {des:6s} Q={q_chk:5.1f}@{fq}MHz (ds {Q})  SRF={srf_chk:6.0f} MHz (ds {srf})  Leff@100MHz={L100:6.1f} nH  Cp={Cp*1e15:.0f} fF")

# FH 0805CG C0G caps on the board, plus the retune/3rd-trap options
CAPS = [("0805CG100J500NT", 10e-12, "C14 C16"), ("0805CG180J500NT", 18e-12, "C15"),
        ("0805CG220J500NT", 22e-12, "C1 C2"), ("0805CG270J500NT", 27e-12, "C7"),
        ("0805CG330J500NT", 33e-12, "C3"), ("0805CG470J500NT", 47e-12, "C8"),
        ("0805CG101J500NT", 100e-12, "C10"), ("0805CG331J500NT", 330e-12, "C5"),
        ("0805CG102J500NT", 1e-9, "C4 C13"),
        ("0805CG3R3C500NT", 3.3e-12, "option: parallel with 22p for 25.3p C7"),
        ("0805CG300J500NT", 30e-12, "option: 3rd trap"), ("0805CG430J500NT", 43e-12, "option: retuned C8")]
ESL = 0.8e-9
for pn, C, des in CAPS:
    esr = 0.10 + 0.10 * np.sqrt(f / 100e6)
    Z = 1 / (1j * w * C) + 1j * w * ESL + esr
    srf = 1 / (2 * np.pi * np.sqrt(ESL * C)) / 1e6
    q150 = (1 / (2 * np.pi * 150e6 * C) - 2 * np.pi * 150e6 * ESL) / (0.10 + 0.10 * np.sqrt(1.5))
    write(f"FH_{pn}", Z, [f"FH {pn} {C*1e12:g} pF 0805 C0G ({des})",
          "FH publishes no RF data: typical 0805 C0G model, ESL=0.8 nH, ESR=0.10+0.10*sqrt(f/100MHz) ohm",
          "Generated by make_s2p.py - an estimate, not a measurement"])
    report.append(f"{pn:18s} {des[:22]:22s} SRF={srf:6.0f} MHz  Q@150MHz={q150:6.0f}")

# FH 150 ohm resistor R4
Zr = 150 + 1j * w * 0.7e-9; Zcp = 1 / (1j * w * 0.05e-12); Z = Zr * Zcp / (Zr + Zcp)
write("FH_RS-05K1500FT", Z, ["FH RS-05K1500FT 150 ohm 0805 (R4)", "Model: 150 ohm + 0.7 nH, || 0.05 pF",
      "Generated by make_s2p.py - an estimate, not a measurement"])
print("\n".join(report))
